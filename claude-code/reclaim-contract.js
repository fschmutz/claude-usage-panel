// Dev-cache reclaim, the pure contract (the Node port). Mirrors
// lib/pure/reclaim.js (GNOME) and ClaudeUsageCore/Reclaim.swift (macOS) 1:1;
// tests/fixtures/reclaim.json pins the catalog and the rules. The I/O lives in
// reclaim.js. No Node built-ins here.
//
// This is the one feature in this repo that DELETES things, so it is built the
// other way round from everything else: the catalog is a fixed, reviewable
// list of exact paths (never a glob, never a walk looking for things that look
// deletable), every entry says what it is and what losing it costs, nothing
// happens without an explicit choice, and what does happen is a move to the
// trash - recoverable by the desktop's own undo - never an unlink.
//
// Two kinds of entry, and the difference is the whole point:
//   cache / logs - regenerated by the tool that wrote them. Safe.
//   history      - your own work: transcripts you can still resume, and the
//                  only local record of what your plan was spent on. Never
//                  offered by default; a caller has to ask for it by name.

