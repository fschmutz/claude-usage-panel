/**
 * The catalog for one platform, with every `{placeholder}` expanded.
 * @param {object} dirs {home, claudeHome, codexHome, xdgCache, xdgConfig}
 * @param {string} platform 'darwin' | 'linux' | …
 * @returns {Array<{id, tool, label, kind, note, path}>} entries this platform has
 */
export function reclaimCatalog(dirs, platform) {
  const expand = (spec) => spec.replace(/\{(\w+)\}/g, (m, key) => dirs[key] ?? m);
  const out = [];
  for (const entry of CATALOG) {
    const spec = entry.paths[platform] ?? entry.paths.all;
    if (!spec) continue;
    const {paths: _paths, ...rest} = entry;
    out.push({...rest, path: expand(spec)});
  }
  return out;
}

/** Every id the catalog knows, in catalog order. */
export function reclaimIds() {
  return CATALOG.map((e) => e.id);
}

/** The entries offered when the user has not named any: the regenerated ones,
 *  never their own history. */
export function reclaimDefaultIds() {
  return CATALOG.filter((e) => e.kind !== 'history').map((e) => e.id);
}

/**
 * What a reclaim run would do. Nothing is decided anywhere else: a caller
 * hands in the scanned entries and the ids the user chose, and gets back
 * exactly what to move, what to leave, and why.
 *
 * @param {Array<{id, kind, path, bytes: ?number}>} scanned the catalog, sized
 * @param {?string[]} ids the ids the user chose; null means "the safe ones"
 * @param {boolean} includeHistory the user asked for a `history` entry BY NAME
 *   and confirmed it. Without this a history entry is refused even when named.
 * @returns {{targets: Array<object>, totalBytes: number,
 *            refused: Array<{id: string, why: 'unknown'|'history'|'empty'}>}}
 */
export function reclaimPlan(scanned, ids = null, {includeHistory = false} = {}) {
  const byId = new Map(scanned.map((e) => [e.id, e]));
  const chosen = ids ?? reclaimDefaultIds();
  const targets = [];
  const refused = [];
  for (const id of chosen) {
    const entry = byId.get(id);
    if (!entry) {
      refused.push({id, why: 'unknown'});
      continue;
    }
    // A history entry is never swept up by a default run, and never moved by
    // a named one either unless the caller says out loud that it meant it.
    if (entry.kind === 'history' && !includeHistory) {
      refused.push({id, why: 'history'});
      continue;
    }
    if (!entry.bytes) {
      refused.push({id, why: 'empty'});
      continue;
    }
    targets.push(entry);
  }
  return {targets, totalBytes: targets.reduce((n, e) => n + e.bytes, 0), refused};
}

const UNITS = ['B', 'KB', 'MB', 'GB', 'TB'];

/** "1.4 GB" - one decimal from KB up, whole bytes below. Identical in every
 *  port so a dry run and the log that follows it never disagree. */
export function formatBytes(bytes) {
  const n = Number(bytes);
  if (!Number.isFinite(n) || n < 0) return '-';
  if (n < 1024) return `${Math.round(n)} B`;
  let value = n;
  let unit = 0;
  while (value >= 1024 && unit < UNITS.length - 1) {
    value /= 1024;
    unit += 1;
  }
  return `${value.toFixed(1)} ${UNITS[unit]}`;
}
